import 'package:flutter_test/flutter_test.dart';
import 'package:qr_scan_industry/src/data/data_provider.dart';

/// Правило сброса кэша при смене аккаунта.
///
/// Появилось из живой жалобы: обходчик сменил учётную запись, а справочник ЗИП
/// остался от прошлой компании. Почти все справочники синхронизация
/// перезаписывает целиком и потому самоисцеляются; каталог ЗИП — нет, он
/// инкрементальный, и его курсор переживал выход. Проход видел непустой бокс и
/// живой курсор, просил «что изменилось с тех пор» — и чужие позиции
/// оставались навсегда.
///
/// Правило намеренно вынесено в чистую функцию: три его ветки легко «упростить»
/// при следующей правке, а цена ошибки — либо чужие данные на экране, либо
/// выброшенный офлайн-кэш у своего же пользователя.
void main() {
  group('shouldResetCacheForAccount', () {
    test('другой пользователь — кэш сбрасываем', () {
      expect(
        shouldResetCacheForAccount(stored: 'user-a', incoming: 'user-b'),
        isTrue,
      );
    });

    test('тот же пользователь — кэш сохраняем', () {
      // Иначе повторный вход стоил бы обходчику всех справочников, а без сети
      // он остался бы вообще ни с чем.
      expect(
        shouldResetCacheForAccount(stored: 'user-a', incoming: 'user-a'),
        isFalse,
      );
    });

    test('кэш ничей — сбрасываем', () {
      // Первый вход после установки и после обновления с версии, которая
      // отметку не вела. Чей кэш в боксах — неизвестно, значит чужой.
      expect(
        shouldResetCacheForAccount(stored: '', incoming: 'user-a'),
        isTrue,
      );
    });

    test('вошёл неизвестно кто — не трогаем ничего', () {
      // Офлайн-вход по локальной записи без uuid. Выбросить рабочий кэш и
      // остаться без сети и без данных — худший из возможных исходов.
      expect(
        shouldResetCacheForAccount(stored: 'user-a', incoming: ''),
        isFalse,
      );
      expect(
        shouldResetCacheForAccount(stored: '', incoming: ''),
        isFalse,
      );
    });
  });
}
