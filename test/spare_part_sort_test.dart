import 'package:flutter_test/flutter_test.dart';
import 'package:qr_scan_industry/src/model/spare_part.dart';

/// Порядок каталога ЗИП.
///
/// `String.compareTo` сравнивает кодовые единицы UTF-16, и на кириллице это
/// ломает алфавит: `Ё` стоит до `А`, а все строчные — после всех прописных.
/// В справочнике, где часть номенклатуры заведена с заглавной, а часть нет,
/// список выглядел перемешанным, и найти позицию прокруткой было нельзя.
SparePart part(String name) => SparePart(uuid: 'uuid-$name', name: name);

List<String> sorted(List<String> names) {
  final list = [for (final name in names) part(name)]
    ..sort(SparePart.compareByName);
  return [for (final item in list) item.name];
}

void main() {
  group('SparePart.compareByName', () {
    test('регистр не влияет на порядок', () {
      // До правки «болт М6» уезжал ниже «Ящика»: строчная «б» (U+0431) больше
      // прописной «Я» (U+042F).
      expect(
        sorted(['Ящик', 'болт М6', 'Автомат']),
        ['Автомат', 'болт М6', 'Ящик'],
      );
    });

    test('«ё» стоит на своём месте, а не впереди каталога', () {
      // До правки «Ёмкость» (U+0401) оказывалась раньше «Автомата» (U+0410),
      // то есть в самом начале справочника.
      expect(
        sorted(['Ёмкость', 'Автомат', 'Ящик', 'Жила']),
        ['Автомат', 'Ёмкость', 'Жила', 'Ящик'],
      );
    });

    test('«ё» и «е» соседствуют, как в словаре', () {
      expect(
        sorted(['Ершик', 'Ёлка', 'Единица']),
        ['Единица', 'Ёлка', 'Ершик'],
      );
    });

    test('одинаковые названия в разном регистре не «плавают»', () {
      // Ключи сортировки совпадают, поэтому порядок решает исходное название —
      // иначе он менялся бы от прохода к проходу.
      expect(sorted(['болт', 'Болт']), ['Болт', 'болт']);
      expect(sorted(['Болт', 'болт']), ['Болт', 'болт']);
    });

    test('латиница и цифры идут до кириллицы, между собой — по алфавиту', () {
      // «М12» и «М6» здесь с кириллической «М» — как их и заводят в
      // справочнике, — поэтому они после «Автомата», а не перед ним.
      expect(
        sorted(['М12', 'DIN 933', 'Автомат', 'М6', '10.06.5']),
        ['10.06.5', 'DIN 933', 'Автомат', 'М12', 'М6'],
      );
    });
  });
}
