import 'package:flutter_dotenv/flutter_dotenv.dart';

/// Фича-флаги, зависящие от окружения (задаются в `.env`).
class FeatureFlags {
  /// Раздел ППР (кнопка «ППР» на главном экране, экран задач ППР и группа
  /// «ППР» в списке задач оборудования).
  ///
  /// Эндпоинты `/v1/company/ppr/` теперь есть и на dev, и на проде, поэтому
  /// раздел включён по умолчанию. Флаг оставлен как аварийный выключатель:
  /// `PPR_ENABLED=false` в `.env` полностью отключает раздел — синхронизация
  /// ППР не ходит в сеть и раздел не показывается даже при наличии кэша.
  static bool get pprEnabled =>
      (dotenv.env['PPR_ENABLED'] ?? '').trim().toLowerCase() != 'false';
}
