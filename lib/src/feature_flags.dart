import 'package:flutter_dotenv/flutter_dotenv.dart';

/// Фича-флаги, зависящие от окружения (задаются в `.env`).
class FeatureFlags {
  /// Раздел ППР (группа «ППР» в списке задач).
  ///
  /// Эндпоинты `/v1/company/ppr/` есть только на dev-бэкенде; на проде их
  /// пока нет, поэтому по умолчанию раздел выключен — код остаётся в сборке,
  /// но не синхронизируется и не показывается.
  ///
  /// Включается строкой `PPR_ENABLED=true` в `.env` (в dev-блоке). Когда
  /// прод начнёт поддерживать ППР — добавить её и в прод-блок.
  static bool get pprEnabled =>
      (dotenv.env['PPR_ENABLED'] ?? '').trim().toLowerCase() == 'true';
}
