/// Показ и разбор количественных значений: остатков ЗИП, расхода, наработки.
///
/// Разделитель дробной части на экране — **запятая**, как в веб-админке и как
/// принято в русской записи чисел. Раньше каждое место печатало `double`
/// как есть, и обходчик видел «0.25» там, где администратор в той же карточке
/// видит «0,25».
///
/// Разделитель ввода — **и запятая, и точка**: на клавиатуре телефона там
/// обычно один символ, и какой именно — зависит от раскладки и производителя.
library;

/// Число для показа: целое — без дробной части («4», а не «4.0»), дробное — с
/// запятой («0,25»).
///
/// Целое печатается через `toInt()`, потому что сервер отдаёт `Numeric(14, 4)`,
/// и «40.0000» в цехе читать неудобно.
String formatQuantity(double value) {
  if (value == value.roundToDouble()) return value.toInt().toString();
  return value.toString().replaceAll('.', ',');
}

/// Разбор числа, введённого человеком. `null` — ввели не число.
///
/// Запятая и точка равнозначны: поле показывает значение с запятой, а набрать
/// его могут через точку — отвечать на это «значение должно быть числом»
/// нельзя.
double? parseQuantity(String? raw) {
  if (raw == null) return null;
  return double.tryParse(raw.trim().replaceAll(',', '.'));
}
