import 'package:flutter/foundation.dart';

/// Ответ на запрос с токеном [requestToken] относится к живой сессии: запрос
/// начат в текущей сессии ([requestSession] == [currentSession]), тот же
/// токен до сих пор вошёл ([currentToken]) и отказ «доступ закрыт» по нему
/// ещё не получали ([blockedToken]).
///
/// Иначе состояние доступа из этого ответа записывать нельзя: он мог
/// запоздать и затереть более свежий отказ — например, `/user/me`, начатый
/// до того, как роль сняли, вернул бы ещё активный профиль поверх
/// запомненной блокировки (`DataProviderSync.syncAccessProfile`).
///
/// Сессию сравниваем по номеру, а не только по токену: токен нового входа
/// может совпасть с прежним (время в нём — с точностью до секунды), и
/// запоздалый запрос прошлой сессии прошёл бы проверку и перезаписал
/// профиль, сохранённый входом. Номер растёт на каждом входе и выходе
/// (`DataProvider.startAccessSession`).
///
/// Отдельной чистой функцией — ради теста без Hive и `GlobalState`.
bool isLiveAccessSession({
  required String requestToken,
  required String? currentToken,
  required String? blockedToken,
  required int requestSession,
  required int currentSession,
}) =>
    requestSession == currentSession &&
    currentToken == requestToken &&
    blockedToken != requestToken;

/// Порядок ответов профиля доступа одной сессии.
///
/// Проверка сессии ([isLiveAccessSession]) защищает от ответа, пришедшего
/// после выхода или блокировки, но два запроса **одной** живой сессии она
/// пропускает оба. Летят они параллельно (фоновая синхронизация и
/// обновление по `X-Access-Version` или `access_changed`), и ответы могут
/// прийти наоборот: запоздалый старый профиль лёг бы поверх свежего и
/// вернул снятые права.
///
/// Сравнить сами профили нельзя: `access_version` у сервера непрозрачная
/// строка, порядка у неё нет. Поэтому порядок держим по запросам: каждый
/// берёт номер [begin] до отправки, и записать ответ можно, только если
/// после него не записали ответ более позднего запроса ([tryApply]).
class AccessResponseOrder {
  int _issued = 0;
  int _applied = 0;

  /// Номер запроса — брать до отправки.
  int begin() => ++_issued;

  /// Ответ запроса [ticket] можно записать — он не старше уже записанного.
  /// Возвращает `true` и запоминает его; вызывать в момент записи.
  bool tryApply(int ticket) {
    if (ticket <= _applied) return false;
    _applied = ticket;
    return true;
  }
}

/// Ответ сервера поднимает флаг «сессия истекла» (`DataProvider.authExpired`).
///
/// Флаг раньше ставили только очереди отправки, и если отправлять было
/// нечего, токен, который сервер больше не принимает (выдан другим сервером,
/// сменили ключ подписи), не замечал никто: синхронизация молча падала на 401,
/// а обходчик смотрел на старый кэш и «не видел» новых задач. Теперь решение
/// принимает общий HTTP-клиент по **каждому** ответу с токеном — справочники,
/// задачи, `/user/me`, SSE, очереди.
///
/// Поднимает только 401 — токен не принят. **Снять флаг ответ не может**:
/// отвергнутый токен в этой же сессии годным не станет, а успешный ответ мог
/// быть ответом на запрос, ушедший раньше 401, — поздний 200 гасил бы свежую
/// «Сессия истекла», и открытая форма, закрывшись, уже не выводила бы на вход.
/// Снимает флаг только новая сессия: вход или выход (сеттер
/// `GlobalState.authUser`).
///
/// Поднять флаг может только ответ живой сессии: запрос ушёл в текущей сессии
/// ([requestSession] == [currentSession]) и с токеном того, кто вошёл
/// сейчас. Иначе 401 на запрос, отправленный до выхода, поднял бы «Сессия
/// истекла» над новым входом (номер сессии), а запрос самого входа — `/user/me`
/// со свежим токеном до его сохранения — тронул бы флаг прежней (токен).
/// Запрос без токена (сам вход) о сессии ничего не говорит.
bool raisesAuthExpired({
  required int statusCode,
  required String? requestToken,
  required String? currentToken,
  required int requestSession,
  required int currentSession,
}) =>
    statusCode == 401 &&
    requestToken != null &&
    requestToken == currentToken &&
    requestSession == currentSession;

/// Почему сессию закрыли без участия обходчика — что объяснить на экране
/// входа.
enum SessionEndReason {
  /// Сервер перестал принимать токен (401) во время работы.
  expired,

  /// Сохранённую сессию выдал другой сервер: приложение пересобрано или
  /// перенастроено на другой `API_ENDPOINT` (`data/session_server.dart`).
  serverChanged,
}

/// Окно, которое экран входа ещё не показал: причина и логин, который
/// подставить в поле, — войти нужно тем же аккаунтом, чтобы ушли его
/// неотправленные записи.
class SessionEndNotice {
  final SessionEndReason reason;
  final String login;

  const SessionEndNotice(this.reason, this.login);
}

/// Пора выводить обходчика на экран входа по истёкшей сессии.
///
/// Решение продукта: сессию, которую сервер не принимает, не держим —
/// работа «вслепую» на старом кэше хуже, чем повторный вход. Но открытую
/// форму ([openForms] — экран скана, создание и карточка ремонта, разбор
/// конфликта осмотра) не обрываем: введённое пропало бы. Пока она открыта,
/// над ней полоса «Сессия истекла», а «Отправить» кладёт результат в
/// очередь; выход — как только обходчик с неё уйдёт. Неотправленное не
/// теряется: у записей очередей есть владелец, и уйдут они после входа.
bool shouldSignOutExpiredSession({
  required bool expired,
  required bool authorized,
  required int openForms,
}) =>
    expired && authorized && openForms <= 0;

/// Флаг состояния сессии, который поднимают ответы на запросы, —
/// «сессия истекла» у очередей отправки (`DataProvider.authExpired`).
///
/// Запрос, ушедший до выхода, может ответить 401/403 уже после нового входа:
/// без проверки он поднял бы «Сессия истекла» над живой сессией. Токен тут не
/// поможет — у повторного входа он может совпасть с прежним. Поэтому запрос
/// запоминает номер сессии до отправки, и поднять флаг может только ответ
/// текущей. Снимает флаг только новая сессия — см. [raisesAuthExpired].
class SessionGuardedFlag {
  final ValueNotifier<bool> flag;
  final int Function() currentSession;

  SessionGuardedFlag(this.flag, this.currentSession);

  /// Поднимает флаг, если запрос отправлен в текущей сессии
  /// [requestSession]; ответ прошлой ничего не меняет.
  void raise({required int requestSession}) {
    if (requestSession != currentSession()) return;
    flag.value = true;
  }
}
