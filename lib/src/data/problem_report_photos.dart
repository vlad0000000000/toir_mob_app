/// Снимки заявки «Другое» не загрузились — повторить позже или бросить.
///
/// Задача на сервере к этому моменту уже создана, и повтор касается только
/// снимков. Повторяем то, что лечится временем: обрыв связи, сбой сервера,
/// протухший или закрытый доступ (уйдёт после повторного входа). Отказ по
/// существу — бросаем, иначе запись гоняла бы те же кадры по кругу:
/// - 409 — задачу уже взяли в работу, сервер больше не принимает к ней фото
///   сообщения о проблеме;
/// - 403 — у роли нет ни права изменения задач, ни права создания осмотров
///   (или сервер прошлой версии, где фото требовали `tasks.edit`);
/// - 404, 410, 413, 422 — задачи или кадров уже нет, файл не принят.
///
/// Брошенные снимки не пропадают бесследно: те же кадры уходят в осмотре,
/// по которому заявка заведена, — администратор увидит их в истории
/// осмотров.
bool isRetryableProblemPhotoError(Object error) {
  if (error is AuthExpiredException) return true;
  if (error is ServerFailureException) return error.isTransient;
  return isOfflineError(error);
}

/// Создание заявки отклонено так, что повтор ответит тем же — ждать нечего:
/// - 410 — сервер узнал ключ повтора, но созданную по нему задачу уже
///   удалили: заявка была доставлена;
/// - 409 — такая задача уже есть (`PeriodicTaskDuplicateError`) или ключ
///   уже использован с другим телом запроса. Тело у записи от повтора к
///   повтору не меняется, так что второе — запись прошлой версии с ключом,
///   выданным до выкладки сервера.
///
/// 404 сюда не входит — см. [isProblemReportRejected]. Прочие отказы
/// по-прежнему повторяются фоном: бросать запись по отказу, который может
/// пройти, нельзя.
bool isProblemReportSettled(Object error) =>
    error is ServerFailureException &&
    (error.statusCode == 410 || error.statusCode == 409);

/// Создание заявки отклонено по существу: фоновый повтор каждые 120 секунд
/// ответил бы тем же, но бросать запись нельзя — задачи «Проблема» тогда не
/// будет вовсе. Это любой отказ 4xx, кроме временных (408, 429) и уже
/// разобранных в [isProblemReportSettled] (409, 410); 401 сюда не попадает —
/// это [AuthExpiredException], заявка уйдёт после входа. Чаще всего:
/// - 404 — оборудования сервер не видит: удалено, а на сервере до `06b145f`
///   — ещё и чужое подразделение (там к чужому пускали только сам осмотр, не
///   отдельную заявку — п. 8.1 `docs/backend-equipment-scope.md`). Заявки,
///   отклонённые так до выкладки, уйдут сами: выкладка меняет версию доступа,
///   и `retryNoRightsRejections` снимает пометку;
/// - 403 — у роли нет права на заявку;
/// - 400, 422 — сервер не принял данные.
///
/// Раньше отклонённой становилась только заявка с 404, а 403 и 422 тихо
/// повторялись вечно — и «Синхронизировать данные» обещал, что они «уйдут
/// сами». Теперь запись остаётся в очереди с причиной
/// ([PeriodicTaskRequest.rejectedReason], [problemReportRejectionReason]),
/// фон её не трогает, а «Синхронизировать данные», смена доступа и лист на
/// главной пробуют снова.
bool isProblemReportRejected(Object error) {
  if (error is! ServerFailureException) return false;
  final status = error.statusCode;
  if (status < 400 || status >= 500) return false;
  return !const {408, 409, 410, 429}.contains(status);
}

/// Прежняя формулировка [ProblemReportStrings.rejectedNotFound] (до бэкенда
/// `06b145f`) — так её сохранила в заявках версия `8e742ed`. Меняя текст
/// снова, добавьте сюда и нынешний.
const String _legacyRejectedNotFound =
    'Сервер не нашёл оборудование — возможно, оно в другом подразделении. '
    'Осмотр отправлен, но задача по проблеме не создана. Повторите '
    '«Синхронизировать данные» позже или сообщите администратору.';

/// Причина отказа, уже лежащая в заявке, — для показа.
///
/// Причина хранится в записи текстом ([PeriodicTaskRequest.rejectedReason]).
/// Заявки, отклонённые прошлой версией, несут прежние слова: без перевода лист
/// на главной показывал бы устаревшее «в другом подразделении», а окно
/// синхронизации — одну причину двумя пунктами (причины в нём склеиваются по
/// тексту). На повтор текст не влияет: заявки повторяются все.
String problemReportStoredReason(String? stored) {
  final text = (stored ?? '').trim();
  if (text.isEmpty) return ProblemReportStrings.rejectedOther;
  if (text == _legacyRejectedNotFound) {
    return ProblemReportStrings.rejectedNotFound;
  }
  return text;
}

/// Причина отказа заявки — для листа на главной и окна синхронизации.
/// Осмотр «Другое» во всех случаях уже на сервере: текст говорит, что не
/// создана только задача для администратора.
String problemReportRejectionReason(Object error) {
  final status = error is ServerFailureException ? error.statusCode : null;
  return switch (status) {
    404 => ProblemReportStrings.rejectedNotFound,
    403 => ProblemReportStrings.rejectedNoRights,
    _ => ProblemReportStrings.rejectedOther,
  };
}
