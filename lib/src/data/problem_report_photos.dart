import '../utils/offline_error.dart';

/// Снимки заявки «Другое» не загрузились — повторить позже или бросить.
///
/// Задача на сервере к этому моменту уже создана, и повтор касается только
/// снимков. Повторяем то, что лечится временем: обрыв связи, сбой сервера,
/// протухший или закрытый доступ (уйдёт после повторного входа). Отказ по
/// существу — бросаем, иначе запись гоняла бы те же кадры по кругу:
/// - 409 — задачу уже взяли в работу, сервер больше не принимает к ней фото
///   сообщения о проблеме;
/// - 403 — у роли нет ни права изменения задач, ни права создания осмотров
///   (или сервер прошлой версии, где фото требовали `tasks.edit`);
/// - 404, 410, 413, 422 — задачи или кадров уже нет, файл не принят.
///
/// Брошенные снимки не пропадают бесследно: те же кадры уходят в осмотре,
/// по которому заявка заведена, — администратор увидит их в истории
/// осмотров.
bool isRetryableProblemPhotoError(Object error) {
  if (error is AuthExpiredException) return true;
  if (error is ServerFailureException) return error.isTransient;
  return isOfflineError(error);
}

/// Создание заявки отклонено так, что повтор ответит тем же — ждать нечего:
/// - 410 — сервер узнал ключ повтора, но созданную по нему задачу уже
///   удалили: заявка была доставлена;
/// - 409 — такая задача уже есть (`PeriodicTaskDuplicateError`) или ключ
///   уже использован с другим телом запроса. Тело у записи от повтора к
///   повтору не меняется, так что второе — запись прошлой версии с ключом,
///   выданным до выкладки сервера.
///
/// Прочие отказы по-прежнему повторяются: у очереди заявок пометки отказа
/// нет, и бросать запись по отказу, который может пройти, нельзя.
bool isProblemReportSettled(Object error) =>
    error is ServerFailureException &&
    (error.statusCode == 410 || error.statusCode == 409);
