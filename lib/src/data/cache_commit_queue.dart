import 'dart:async';

/// Очередь фиксации результатов синхронизации в кэш аккаунта.
///
/// Синхронизация живёт секунды, и за это время обходчик успевает выйти и
/// войти другим. Сверить «чей это проход» один раз перед записью мало: запись
/// — это несколько `await` подряд (очистка, заливка, курсор, отметки), и
/// смена аккаунта вклинивается между ними. Тогда прошлый проход дописывает
/// свои данные поверх уже вычищенного кэша — и поверх того, что успел
/// загрузить новый аккаунт.
///
/// Поэтому фиксации и очистка кэша идут **строго по одной**, а поколение
/// сверяется внутри очереди, непосредственно перед записью:
///
/// * запись, начавшаяся до смены аккаунта, доходит до конца, и очистка,
///   вставшая за ней, стирает её результат;
/// * всё, что встало в очередь после [invalidate], видит новое поколение и
///   ничего не пишет.
///
/// Внутри фиксации — только запись в Hive и в память, без сети: очередь
/// общая, и сетевой запрос в ней задержал бы все остальные проходы. Вложенная
/// фиксация (или очистка) изнутри фиксации повесит очередь навсегда.
///
/// Отдельным классом без Hive — чтобы порядок можно было проверить тестом.
class CacheCommitQueue {
  int _generation = 0;
  Future<void> _tail = Future<void>.value();

  /// Текущее поколение кэша. Проход запоминает его на старте и передаёт в
  /// [commit].
  int get generation => _generation;

  /// Кэш сменил владельца с момента [generation] — писать нельзя.
  bool isStale(int generation) => generation != _generation;

  /// Аккаунт сменился: всё, что запросит фиксацию с прежним поколением, писать
  /// уже не будет. Синхронно, до очистки, — чтобы отказ начался сразу, а не
  /// когда очередь дойдёт до самой очистки.
  void invalidate() => _generation++;

  /// Выполняет [body] в очереди, если поколение [generation] ещё текущее.
  ///
  /// `false` — запись отброшена: проход принадлежит прошлому аккаунту.
  Future<bool> commit(int generation, Future<void> Function() body) {
    return _enqueue(() async {
      if (isStale(generation)) return false;
      await body();
      return true;
    });
  }

  /// Выполняет [body] в очереди без сверки поколения — для самой очистки
  /// кэша, которая должна дождаться уже идущей записи.
  Future<void> run(Future<void> Function() body) => _enqueue(body);

  Future<T> _enqueue<T>(Future<T> Function() body) {
    final previous = _tail;
    final done = Completer<void>();
    _tail = done.future;
    // Хвост завершается всегда, даже если [body] упал: иначе одна ошибка
    // записи остановила бы все следующие фиксации.
    return previous.then((_) => body()).whenComplete(done.complete);
  }
}
