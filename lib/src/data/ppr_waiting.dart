import '../model/ppr.dart';

// Ждущие задачи ППР (бэкенд `6296b61`) и область обходчика.
//
// В «Задачах» обходчик видит только задачи своей области (решение 18.11).
// `GET /v1/company/ppr/{uuid}` сам отдаёт в `tasks[]` только задачи области
// того, кто спрашивает (подтверждено бэкендом к `811c4dc`), поэтому ждущие
// задачи берутся из ответа ППР как есть. Раньше каждую проверяли отдельным
// `GET /periodic_task/{uuid}` и кэшировали ответ на 30 минут — это лишние
// запросы.
//
// После смены доступа прежний состав ППР — ещё старой области: ждущие задачи
// не показываются, пока ППР не перечитаны (`DataProvider.refreshAccess`).

/// Ключ кэша видимости прошлой версии в `stringBox`. Больше не пишется —
/// удаляется при старте и при сбросе данных аккаунта.
const String legacyPprWaitingVisibilityKey = 'ppr_waiting_visibility';

/// Ждущие задачи [ppr] для обходчика. Только у ППР «В работе»: сервер ставит
/// признак лишь им. [accessStale] — доступ сменился, а ППР ещё не
/// перечитаны: состав прежней области не показываем.
List<PprWaitingTask> visibleWaitingTasks(Ppr ppr, {bool accessStale = false}) {
  if (accessStale || !ppr.isInProgress) return const [];
  return ppr.waitingTasks;
}
