/// Код состояния «В работе» на сервере (`EquipmentState.IN_OPERATION`).
const String inOperationState = 'in_operation';

/// Новые задачи по оборудованию в состоянии [state] не создаются.
///
/// Правило сервера (бэкенд `5e60312`, `state_allows_generation`): задачи по
/// расписанию и ТО появляются только у оборудования «В работе». Без состояния
/// — тоже пауза: сервер требует именно `in_operation`. Обходчик меняет
/// состояние сам, поэтому должен знать об этом заранее.
///
/// На уже выданное пауза не влияет: выданные задачи, заявки «Проблема» и ППР
/// работают как обычно.
bool isTaskGenerationPaused(String? state) => state != inOperationState;
