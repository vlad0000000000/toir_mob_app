/// Почему сервер отказался принять черновик или правку.
///
/// Вид конфликта определяется один раз — в момент отказа, когда под рукой и
/// текст сервера, и свежая карточка ремонта. Экран разрешения им только
/// пользуется: дорассуждать постфактум, без связи, он бы уже не смог.
///
/// Коды хранятся в Hive строками, а не индексами: перестановка значений в
/// перечислении не должна менять смысл сохранённого.
enum RepairConflictKind {
  /// Оборудование занято ремонтом, где ответственный — текущий обходчик.
  /// Единственный случай, когда данные можно перенести в существующий ремонт.
  equipmentBusyMine('equipment_busy_mine'),

  /// Оборудование занято ремонтом другого сотрудника. Переносить нельзя:
  /// чужой расход обходчик подтверждать не вправе.
  equipmentBusyOther('equipment_busy_other'),

  /// Ремонт закрыт администратором — правки не принимаются вовсе.
  repairClosed('repair_closed'),

  /// Ремонт передан другому ответственному — доступа больше нет.
  repairReassigned('repair_reassigned'),

  /// 403 «нет прав», а сервер подтвердил, что ремонт открыт: отказ по правам
  /// роли (подразделение, снятое право), а не по статусу. Очередь такую
  /// пометку сама не снимает — только смена доступа или «Повторить».
  noRights('no_rights'),

  /// Прочий отказ сервера. Отправку можно повторить.
  other('other');

  const RepairConflictKind(this.code);

  final String code;

  static RepairConflictKind fromCode(String? code) {
    for (final kind in values) {
      if (kind.code == code) return kind;
    }
    return other;
  }

  /// Данные можно перенести в существующий ремонт.
  bool get canTransfer => this == equipmentBusyMine;

  /// Повторять отправку бессмысленно — сервер откажет снова.
  /// Отказ по правам не окончательный: доступ могут вернуть.
  bool get isFinal => this != other && this != noRights;
}
