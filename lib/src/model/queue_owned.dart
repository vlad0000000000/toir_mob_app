/// Запись очереди отправки: чья она и для какого сервера.
///
/// Очереди переживают и смену аккаунта, и смену сервера (пересборку
/// приложения под другой `API_ENDPOINT`): стирать несделанную работу нельзя.
/// Поэтому запись уходит, считается и показывается, только когда вошёл её
/// владелец **на её сервере** — `DataProvider.isMine`, правило
/// `isQueueOwner`. Реализуют пять моделей очередей: `Scan`, `UsageUpdate`,
/// `PeriodicTaskRequest`, `PendingRepair`, `PendingRepairUpdate`.
abstract class QueueOwned {
  /// Обходчик, поставивший запись в очередь; `null` — запись прошлой версии.
  String? get ownerUuid;

  /// Сервер, на который запись должна уйти; `null` — запись прошлой версии.
  String? get ownerServer;
}
